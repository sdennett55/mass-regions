export function normalizeTownId(rawTownId: string) {
  return rawTownId
    .trim()
    .toUpperCase()
    .replace(/\d+$/, "")
    .replace(/[.'’]/g, "")
    .replace(/&/g, "AND")
    .replace(/[\s-]+/g, "_");
}

