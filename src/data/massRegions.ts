function createTownRegionRecord<Region extends string>(
  townRegionList: readonly string[],
  regionsByCode: Record<string, Region>,
) {
  const townRegionEntries: Array<[string, Region]> = [];

  for (let index = 0; index < townRegionList.length; index += 2) {
    const town = townRegionList[index];
    const regionCode = townRegionList[index + 1];
    const region = regionsByCode[regionCode];

    if (!town || !region) {
      continue;
    }

    townRegionEntries.push([normalizeTownId(town), region]);
  }

  return Object.fromEntries(townRegionEntries) as Record<string, Region>;
}

const mcbTownToRegion = createTownRegionRecord(
  mcbTownRegionList,
  mcbRegionNamesByCode,
);

const compactMCBTownToRegion = new Map(
  Object.entries(mcbTownToRegion).map(([town, region]) => [
    town.replace(/_/g, ""),
    region,
  ]),
);

export function getCanonicalTownId(rawTownId: string) {
  const normalizedTownId = normalizeTownId(rawTownId);
  return normalizedAliasMap[normalizedTownId] ?? normalizedTownId;
}

export function getRegionColor(region: AnyRegionName, scheme: RegionScheme) {
  return scheme === "mcb"
    ? mcbRegionColors[region as MCBRegionName]
    : regionColors[region as RegionName];
}

export function getRegionTownCount(
  region: AnyRegionName,
  scheme: RegionScheme,
) {
  const legendGroup = getLegendGroups(scheme).find(
    (group) => group.region === region,
  );

  return legendGroup?.townCount ?? 0;
}

export function getRegionForTownId(
  rawTownId: string,
  scheme: RegionScheme = "standard",
): AnyRegionName | undefined {
  const canonicalTownId = getCanonicalTownId(rawTownId);

  if (scheme === "mcb") {
    return (
      mcbTownToRegion[canonicalTownId] ??
      compactMCBTownToRegion.get(canonicalTownId.replace(/_/g, ""))
    );
  }

  return (
    massTownToRegion[canonicalTownId] ??
    compactTownToRegion.get(canonicalTownId.replace(/_/g, ""))
  );
}

export function formatTownLabel(rawTownId: string) {
  const canonicalTownId = getCanonicalTownId(rawTownId);

  if (townDisplayNameOverrides[canonicalTownId]) {
    return townDisplayNameOverrides[canonicalTownId];
  }

  return canonicalTownId
    .toLowerCase()
    .split("_")
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join(" ");
}

function getRegionOrderForScheme(scheme: RegionScheme) {
  return scheme === "mcb" ? mcbRegionOrder : regionOrder;
}

function getTownToRegionForScheme(scheme: RegionScheme) {
  return scheme === "mcb" ? mcbTownToRegion : massTownToRegion;
}

function buildLegendGroups(scheme: RegionScheme): RegionLegendGroup[] {
  const seenTowns = new Set<string>();
  const townsByRegion = new Map<AnyRegionName, string[]>();

  for (const [rawTownId, region] of Object.entries(getTownToRegionForScheme(scheme))) {
    const canonicalTownId = getCanonicalTownId(rawTownId);

    if (seenTowns.has(canonicalTownId)) {
      continue;
    }

    seenTowns.add(canonicalTownId);

    const towns = townsByRegion.get(region) ?? [];
    towns.push(formatTownLabel(canonicalTownId));
    townsByRegion.set(region, towns);
  }

  return getRegionOrderForScheme(scheme).map((region) => {
    const towns = (townsByRegion.get(region) ?? []).sort((townA, townB) =>
      townA.localeCompare(townB),
    );

    return {
      color: getRegionColor(region, scheme),
      region,
      townCount: towns.length,
      towns,
    };
  });
}

const standardLegendGroups = buildLegendGroups("standard");
const mcbLegendGroups = buildLegendGroups("mcb");

export function getLegendGroups(scheme: RegionScheme) {
  return scheme === "mcb" ? mcbLegendGroups : standardLegendGroups;
}
